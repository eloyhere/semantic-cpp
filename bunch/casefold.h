#pragma once

// ===========================================================================
// bunch/casefold.h
//
// Full Unicode case folding, the canonical "compare without case" form used by
// caseless matching.  Case folding is not case conversion: it maps both
// U+00DF LATIN SMALL LETTER SHARP S and U+1E9E LATIN CAPITAL LETTER SHARP S to
// "ss", folds Greek final sigma to sigma, and expands ligatures such as
// U+FB01 LATIN SMALL LIGATURE FI to "fi".  The result of folding already
// folded text is the same text, so repeated folding is idempotent.
//
// The mapping table lives in casefold_data.h and is generated by
// tools/gen_casefold_data.py from Python's str.casefold() (Unicode 15.0.0),
// which implements CaseFolding.txt statuses C + F.  The language-dependent
// Turkic (T) mappings are applied here instead of in the table.
//
// Text enters and leaves as UTF-8.  Ill-formed input is replaced with U+FFFD
// under the same maximal-subpart rules as the rest of the bunch codec, so the
// function never reads past the end of the buffer.
// ===========================================================================

#include "casefold_data.h"
#include "charset.h"
#include "encode.h"

#include <cstdint>
#include <string>
#include <string_view>

namespace bunch
{
namespace detail
{
inline bool isTurkicCaseFoldLanguage(std::string_view language)
{
    return language == "tr" || language == "az";
}
} // namespace detail

// Folds text for caseless comparison.  The language tag only selects the
// Turkic tailoring: with "tr" or "az", U+0049 LATIN CAPITAL LETTER I folds to
// U+0131 LATIN SMALL LETTER DOTLESS I and U+0130 LATIN CAPITAL LETTER I WITH
// DOT ABOVE folds to plain "i" (CaseFolding.txt T mappings).  Every other
// language, including the empty default, uses the full C + F mappings.
inline auto casefold(std::string_view text, std::string_view language = "") -> std::string
{
    const bool turkic = detail::isTurkicCaseFoldLanguage(language);
    std::string output;
    output.reserve(text.size() + text.size() / 8 + 4);

    std::string_view remaining = text;
    while (!remaining.empty())
    {
        const std::uint32_t codepoint = decode(remaining, charset::utf8);
        if (turkic && codepoint == 'I')
        {
            appendUtf8(output, 0x0131); // LATIN SMALL LETTER DOTLESS I
            continue;
        }
        if (turkic && codepoint == 0x0130)
        {
            appendUtf8(output, 'i'); // LATIN SMALL LETTER I
            continue;
        }

        const detail::unicode::CaseFoldEntry *entry = detail::unicode::findCaseFold(codepoint);
        if (entry == nullptr)
        {
            appendUtf8(output, codepoint);
            continue;
        }
        for (std::uint32_t index = 0; index < entry->length; ++index)
        {
            appendUtf8(output, detail::unicode::kCaseFoldPool[entry->offset + index]);
        }
    }
    return output;
}
} // namespace bunch
