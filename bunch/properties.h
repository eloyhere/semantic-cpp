inline constexpr std::uint32_t kMaxCodePoint = 0x10FFFF;

// Returns the range that contains codepoint, or nullptr when the code point is
// not covered.  The ranges must be sorted by first and must not overlap.
template <typename Range>
constexpr auto findRange(const Range *ranges, std::size_t count, std::uint32_t codepoint)
    -> const Range *
{
    std::size_t low = 0;
    std::size_t high = count;
    while (low < high)
    {
        const std::size_t middle = low + (high - low) / 2;
        if (ranges[middle].last < codepoint)
        {
            low = middle + 1;
        }
        else
        {
            high = middle;
        }
    }
    if (low < count && ranges[low].first <= codepoint)
    {
        return &ranges[low];
    }
    return nullptr;
}
