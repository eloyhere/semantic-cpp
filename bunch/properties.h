// The public enumerations must list exactly the values the generated data
// uses; the last enumerator is checked against the generated name table
// length, which the generator fills in enumeration order.
static_assert(static_cast<std::size_t>(GeneralCategory::unassigned) + 1 ==
                  detail::properties::kCategoryNameCount,
              "GeneralCategory must list every Unicode general category");
static_assert(static_cast<std::size_t>(EastAsianWidth::ambiguous) + 1 ==
                  detail::properties::kWidthNameCount,
              "EastAsianWidth must list every Unicode East_Asian_Width value");
static_assert(static_cast<std::size_t>(Script::unknown) + 1 ==
                  detail::properties::kScriptNameCount,
              "Script must list every Unicode script plus Unknown");

// Returns the General_Category of a code point.  Unassigned code points and
// values above U+10FFFF report GeneralCategory::unassigned.  Surrogate code
// points report GeneralCategory::surrogate, as in UnicodeData.txt.
constexpr auto generalCategory(std::uint32_t codepoint) -> GeneralCategory
{
    if (codepoint > detail::properties::kMaxCodePoint)
    {
        return GeneralCategory::unassigned;
    }
    const detail::properties::CategoryRange *range = detail::properties::findRange(
        detail::properties::kCategoryRanges, detail::properties::kCategoryRangeCount,
        codepoint);
    return range != nullptr ? static_cast<GeneralCategory>(range->category)
                            : GeneralCategory::unassigned;
}

// Returns the primary Script of a code point.  Unassigned code points,
// surrogate code points, and values above U+10FFFF report Script::unknown.
// Script_Extensions is not consulted.
constexpr auto script(std::uint32_t codepoint) -> Script
{
    if (codepoint > detail::properties::kMaxCodePoint)
    {
        return Script::unknown;
    }
    const detail::properties::ScriptRange *range = detail::properties::findRange(
        detail::properties::kScriptRanges, detail::properties::kScriptRangeCount, codepoint);
    return range != nullptr ? static_cast<Script>(range->script) : Script::unknown;
}

// Returns the East_Asian_Width of a code point.  Unassigned code points use
// the UAX #11 @missing defaults, so unassigned code points in the CJK blocks
// are Wide and everything else is Neutral.
constexpr auto eastAsianWidth(std::uint32_t codepoint) -> EastAsianWidth
{
    if (codepoint > detail::properties::kMaxCodePoint)
    {
        return EastAsianWidth::neutral;
    }
    const detail::properties::WidthRange *range = detail::properties::findRange(
        detail::properties::kWidthRanges, detail::properties::kWidthRangeCount, codepoint);
    return range != nullptr ? static_cast<EastAsianWidth>(range->width)
                            : EastAsianWidth::neutral;
}

// True when the code point has the Alphabetic derived property: letters plus
// letter-like characters such as Other_Alphabetic marks and Nl numbers.
constexpr auto isAlphabetic(std::uint32_t codepoint) -> bool
{
    return codepoint <= detail::properties::kMaxCodePoint &&
           detail::properties::findRange(detail::properties::kAlphabeticRanges,
                                         detail::properties::kAlphabeticRangeCount,
                                         codepoint) != nullptr;
}

// True when the code point has White_Space: the Zs/Zl/Zp separators plus
// U+0009..U+000D and U+0085.  U+200B ZERO WIDTH SPACE is not White_Space.
constexpr auto isWhiteSpace(std::uint32_t codepoint) -> bool
{
    return codepoint <= detail::properties::kMaxCodePoint &&
           detail::properties::findRange(detail::properties::kWhiteSpaceRanges,
                                         detail::properties::kWhiteSpaceRangeCount,
                                         codepoint) != nullptr;
}

// True when the code point has the Uppercase derived property (not simply
// General_Category=Lu).
constexpr auto isUppercase(std::uint32_t codepoint) -> bool
{
    return codepoint <= detail::properties::kMaxCodePoint &&
           detail::properties::findRange(detail::properties::kUppercaseRanges,
                                         detail::properties::kUppercaseRangeCount,
                                         codepoint) != nullptr;
}

// True when the code point has the Lowercase derived property (not simply
// General_Category=Ll).
constexpr auto isLowercase(std::uint32_t codepoint) -> bool
{
    return codepoint <= detail::properties::kMaxCodePoint &&
           detail::properties::findRange(detail::properties::kLowercaseRanges,
                                         detail::properties::kLowercaseRangeCount,
                                         codepoint) != nullptr;
}

// True when the code point has Default_Ignorable_Code_Point: format and
// variation characters that should be invisible when unsupported.
constexpr auto isDefaultIgnorable(std::uint32_t codepoint) -> bool
{
    return codepoint <= detail::properties::kMaxCodePoint &&
           detail::properties::findRange(detail::properties::kDefaultIgnorableRanges,
                                         detail::properties::kDefaultIgnorableRangeCount,
                                         codepoint) != nullptr;
}

// Returns the UCD short name of a category ("Lu", "Nd", "Cn", ...).
// Out-of-range values, which are only reachable through a cast, report "Cn".
constexpr auto generalCategoryName(GeneralCategory value) -> const char *
{
    const std::size_t index = static_cast<std::size_t>(value);
    if (index >= detail::properties::kCategoryNameCount)
    {
        return "Cn";
    }
    return detail::properties::kCategoryNames[index];
}

// Returns the UCD long name of a script ("Latin", "Old_Italic", "Unknown").
// Out-of-range values, which are only reachable through a cast, report
// "Unknown".
constexpr auto scriptName(Script value) -> const char *
{
    const std::size_t index = static_cast<std::size_t>(value);
    if (index >= detail::properties::kScriptNameCount)
    {
        return "Unknown";
    }
    return detail::properties::kScriptNames[index];
}

// Returns the spelled-out East_Asian_Width value ("Neutral", "Narrow",
// "Wide", "Fullwidth", "Halfwidth", "Ambiguous").  Out-of-range values, which
// are only reachable through a cast, report "Neutral".
constexpr auto eastAsianWidthName(EastAsianWidth value) -> const char *
{
    const std::size_t index = static_cast<std::size_t>(value);
    if (index >= detail::properties::kWidthNameCount)
    {
        return "Neutral";
    }
    return detail::properties::kWidthNames[index];
}
