#pragma once

// ===========================================================================
// bunch/properties.h
//
// Unicode character property queries for single code points:
//
//   - General_Category  generalCategory(), generalCategoryName()
//   - Script            script(), scriptName()
//   - East_Asian_Width  eastAsianWidth(), eastAsianWidthName()
//   - Alphabetic, White_Space, Uppercase, Lowercase, and
//     Default_Ignorable_Code_Point as the predicates isAlphabetic(),
//     isWhiteSpace(), isUppercase(), isLowercase(), and isDefaultIgnorable().
//
// The data is Unicode 15.0.0 and comes from the Character Database files
// UnicodeData.txt, Scripts.txt, EastAsianWidth.txt,
// DerivedCoreProperties.txt, and PropList.txt.  bunch/properties_data.h holds
// the compressed sorted range tables and name tables; it is generated by
// tools/gen_properties_data.py and must not be edited by hand.
//
// Every query takes a code point, not a UTF-8 sequence:
//
//     bunch::generalCategory(0x4E2D)  == bunch::GeneralCategory::otherLetter
//     bunch::script(0x4E2D)           == bunch::Script::han
//     bunch::eastAsianWidth(0x4E2D)   == bunch::EastAsianWidth::wide
//
// Values outside the Unicode code space (above U+10FFFF) are reported as
// unassigned (Cn), Script::unknown, and EastAsianWidth::neutral instead of
// being undefined behaviour.  Surrogate code points U+D800..U+DFFF are
// reported exactly as the UCD does: General_Category=Cs and Script=Unknown.
// They are not scalar values, so encoding them as UTF-8 is still an error.
//
// Lookups are constexpr and allocation-free, with O(log n) binary search over
// about 4,000 category, 1,700 script, and 600 East_Asian_Width ranges.
//
// Known limitations:
//   - The data is frozen at Unicode 15.0.0; characters assigned after that
//     version report Cn, Unknown, and Neutral.
//   - script() returns the primary Script property, not Script_Extensions,
//     so characters shared by several scripts report only their primary
//     value (U+3001 IDEOGRAPHIC COMMA is Script=Common, for example).
//   - Emoji properties (Emoji, Emoji_Presentation, Extended_Pictographic),
//     Age, Bidi_Class, and the case mapping tables are not provided here;
//     Bidi_Class lives in bunch/bidi_data.h and case mappings in
//     bunch/unicode.h / bunch/casefold.h.
//   - isUppercase() and isLowercase() are the Unicode derived properties, not
//     the categories Lu and Ll.  U+2160 ROMAN NUMERAL ONE is Nl but is
//     Uppercase, and U+24B6 CIRCLED LATIN CAPITAL LETTER A is So but is also
//     Uppercase; use generalCategory() when the category itself matters.
//   - East_Asian_Width applies the UAX #11 @missing defaults: unassigned code
//     points in the CJK blocks U+3400..U+4DBF, U+4E00..U+9FFF, U+F900..U+FAFF,
//     U+20000..U+2FFFD, and U+30000..U+3FFFD are Wide even though they have no
//     character (U+2FFFD, for example).
//   - Combining_Class, grapheme/word/sentence break properties, and the
//     numeric values of characters are not part of this table.
// ===========================================================================

