"""Header / manifest / report generation for the natural-calendar fit."""

from __future__ import annotations

import json
from pathlib import Path

DATA = Path(__file__).resolve().parents[1] / "temporal" / "natural" / "data"
HEADER = DATA / "waveforms.h"
MANIFEST = DATA / "fit_manifest.json"
REPORT = DATA / "FIT_REPORT.md"


def _f(x: float) -> str:
    return f"{float(x):.17g}"


def _as_envelope(src) -> dict:
    if isinstance(src, dict):
        return src
    omega, cc, ss = src
    return {"omega": float(omega), "degree": len(cc) - 1,
            "cos": [float(v) for v in cc], "sin": [float(v) for v in ss]}


def normalize_sun(src: dict) -> dict:
    poly = [float(v) for v in src.get("polynomial", src.get("poly", []))]
    rate = float(src.get("ratePerCentury", src.get("rate", 0.0)))
    if rate == 0.0 and len(poly) > 1:
        # Polynomial is in xs = x/100; convert the linear coefficient to per-century.
        rate = poly[1] / 100.0
    return {
        "params": int(src.get("params", 0)),
        "rmsDegrees": float(src.get("rmsDegrees", src.get("rms", 0.0))),
        "maxDegrees": float(src.get("maxDegrees", src.get("max", 0.0))),
        "timingSeconds": src.get("timingSeconds", src.get("solar-term timing (s)", {})),
        "ratePerCentury": rate,
        "offset": float(src.get("offset", 0.0)),
        "polynomial": poly,
        "envelopes": [_as_envelope(v) for v in src.get("envelopes", [])],
        "extras": [
            {"amplitude": float(v["amplitude"]), "omega": float(v["omega"]), "phase": float(v["phase"])}
            if isinstance(v, dict) else
            {"amplitude": float(v[0]), "omega": float(v[1]), "phase": float(v[2])}
            for v in src.get("extras", [])
        ],
        "validation": src.get("validation", {}),
    }


def normalize_moon(src: dict) -> dict:
    return {
        "params": int(src.get("params", 0)),
        "rmsDegrees": float(src.get("rmsDegrees", src.get("rms", 0.0))),
        "maxDegrees": float(src.get("maxDegrees", src.get("max", 0.0))),
        "timingSeconds": src.get("timingSeconds", src.get("phase timing (s)", {})),
        "ratePerCentury": float(src.get("ratePerCentury", src.get("rate", 0.0))),
        "offset": float(src.get("offset", 0.0)),
        "polynomial": [float(v) for v in src.get("polynomial", src.get("poly", []))],
        "envelopes": [_as_envelope(v) for v in src.get("envelopes", [])],
        "validation": src.get("validation", {}),
    }


def write_header(payload: dict) -> None:
    sun = payload["sun"]
    moon = payload["moon"]
    cum = payload["cumulative"]
    years = payload["yearLength"]
    lines = []
    lines.append("// Generated by tools/fit_natural.py.  Do not edit by hand.")
    lines.append("// Source: Shouxing calendar data workbook (sxwnl 5.10).")
    lines.append("// Time scale: UTC+8; Julian before 1582-10-15, Gregorian after.")
    lines.append("// Normalization: x = (JD - 2451545.0) / 36525.0 (Julian centuries).")
    lines.append("//")
    lines.append("// The accurate models are the polynomial-envelope models below.  A pure")
    lines.append("// constant-frequency Waveform cannot represent the VSOP87/ELP2000 tables")
    lines.append("// to second-level accuracy; see FIT_REPORT.md for measured errors.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <array>")
    lines.append("#include <cmath>")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace temporal::natural::data")
    lines.append("{")
    lines.append("")
    lines.append("struct Term")
    lines.append("{")
    lines.append("    double amplitude;")
    lines.append("    double omega;")
    lines.append("    double phase;")
    lines.append("};")
    lines.append("")
    lines.append("// Re[e^(i omega x) * sum_m (cosine[m] cos(omega x) + sine[m] sin(omega x)) x^m]")
    lines.append("struct EnvelopeTerm")
    lines.append("{")
    lines.append("    double omega;")
    lines.append("    int degree;")
    lines.append("    std::array<double, 5> cosine;")
    lines.append("    std::array<double, 5> sine;")
    lines.append("};")
    lines.append("")
    lines.append(f"inline constexpr double SunLongitudeRate = {_f(sun['ratePerCentury'])};")
    lines.append(f"inline constexpr double SunLongitudeOffset = {_f(sun.get('offset', 0.0))};")
    lines.append("inline constexpr std::array<double, 6> SunLongitudePolynomial = {{")
    lines.append("    " + ", ".join(_f(v) for v in sun["polynomial"]) + "}};")
    lines.append("")
    lines.append(f"inline constexpr std::array<EnvelopeTerm, {len(sun['envelopes'])}> SunLongitudeEnvelopes = {{{{")
    for env in sun["envelopes"]:
        cc = list(env["cos"]) + [0.0] * (5 - len(env["cos"]))
        ss = list(env["sin"]) + [0.0] * (5 - len(env["sin"]))
        lines.append(f"    {{{_f(env['omega'])}, {env['degree']}, "
                     f"{{{{{', '.join(_f(v) for v in cc[:5])}}}}}, "
                     f"{{{{{', '.join(_f(v) for v in ss[:5])}}}}}}},")
    lines.append("}};")
    lines.append("")
    lines.append(f"inline constexpr std::array<Term, {len(sun['extras'])}> SunLongitudeExtras = {{{{")
    for term in sun["extras"]:
        lines.append(f"    {{{_f(term['amplitude'])}, {_f(term['omega'])}, {_f(term['phase'])}}},")
    lines.append("}};")
    lines.append("")
    lines.append("// Constant-frequency projection at J2000.  This is a coarse convenience")
    lines.append("// array for mathematics::Waveform users; the envelope model above is the")
    lines.append("// authoritative fit (the envelopes carry the amplitude/phase modulation).")
    lines.append(f"inline constexpr std::array<Term, {len(sun['envelopes']) + len(sun['extras'])}> SunLongitudeTerms = {{{{")
    import math as _math
    for env in sun["envelopes"]:
        c = env["cos"][0]
        s = env["sin"][0]
        amp = _math.hypot(c, s)
        phase = _math.atan2(-s, c)
        lines.append(f"    {{{_f(amp)}, {_f(env['omega'])}, {_f(phase)}}},")
    for term in sun["extras"]:
        lines.append(f"    {{{_f(term['amplitude'])}, {_f(term['omega'])}, {_f(term['phase'])}}},")
    lines.append("}};")
    lines.append("")
    lines.append(f"inline constexpr std::array<Term, {len(moon['envelopes'])}> MoonSunTerms = {{{{")
    for env in moon["envelopes"]:
        c = env["cos"][0]
        s = env["sin"][0]
        amp = _math.hypot(c, s)
        phase = _math.atan2(-s, c)
        lines.append(f"    {{{_f(amp)}, {_f(env['omega'])}, {_f(phase)}}},")
    lines.append("}};")
    lines.append("")
    lines.append(f"inline constexpr double MoonSunRate = {_f(moon['ratePerCentury'])};")
    lines.append(f"inline constexpr double MoonSunOffset = {_f(moon.get('offset', 0.0))};")
    lines.append("inline constexpr std::array<double, 4> MoonSunPolynomial = {{")
    lines.append("    " + ", ".join(_f(v) for v in moon["polynomial"]) + "}};")
    lines.append("")
    lines.append(f"inline constexpr std::array<EnvelopeTerm, {len(moon['envelopes'])}> MoonSunEnvelopes = {{{{")
    for env in moon["envelopes"]:
        cc = list(env["cos"]) + [0.0] * (5 - len(env["cos"]))
        ss = list(env["sin"]) + [0.0] * (5 - len(env["sin"]))
        lines.append(f"    {{{_f(env['omega'])}, {env['degree']}, "
                     f"{{{{{', '.join(_f(v) for v in cc[:5])}}}}}, "
                     f"{{{{{', '.join(_f(v) for v in ss[:5])}}}}}}},")
    lines.append("}};")
    lines.append("")
    lines.append("inline constexpr std::array<double, 4> CumulativeDayPolynomial = {{")
    lines.append("    " + ", ".join(_f(v) for v in cum["coefficients"]) + "}};")
    lines.append(f"inline constexpr double CumulativeDayMean = {_f(cum['meanDaysPerMonth'])};")
    lines.append(f"inline constexpr double CumulativeDayIntercept = {_f(cum['coefficients'][0])};")
    lines.append("")
    lines.append("inline constexpr std::array<double, 3> SynodicYearPolynomial = {{")
    lines.append("    " + ", ".join(_f(v) for v in years["synodic"]["coefficients"]) + "}};")
    lines.append("inline constexpr std::array<double, 5> TropicalYearPolynomial = {{")
    lines.append("    " + ", ".join(_f(v) for v in years["tropical"]["coefficients"]) + "}};")
    lines.append("")
    lines.append("inline double sunLongitudeUnwrapped(double jd) noexcept")
    lines.append("{")
    lines.append("    const double x = (jd - 2451545.0) / 36525.0;")
    lines.append("    const double xs = x / 100.0;")
    lines.append("    double v = 0.0;")
    lines.append("    double p = 1.0;")
    lines.append("    for (int i = 0; i < 6; ++i) { v += SunLongitudePolynomial[i] * p; p *= xs; }")
    lines.append("    for (const EnvelopeTerm &e : SunLongitudeEnvelopes)")
    lines.append("    {")
    lines.append("        const double c = std::cos(e.omega * x);")
    lines.append("        const double s = std::sin(e.omega * x);")
    lines.append("        double q = 1.0;")
    lines.append("        for (int m = 0; m <= e.degree; ++m)")
    lines.append("        {")
    lines.append("            v += (e.cosine[m] * c + e.sine[m] * s) * q;")
    lines.append("            q *= xs;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    for (const Term &t : SunLongitudeExtras) v += t.amplitude * std::cos(t.omega * x + t.phase);")
    lines.append("    return v - SunLongitudeOffset;")
    lines.append("}")
    lines.append("")
    lines.append("inline double sunLongitude(double jd) noexcept")
    lines.append("{")
    lines.append("    const double v = std::fmod(sunLongitudeUnwrapped(jd), 360.0);")
    lines.append("    return v < 0.0 ? v + 360.0 : v;")
    lines.append("}")
    lines.append("")
    lines.append("inline double moonSunDifferenceUnwrapped(double jd) noexcept")
    lines.append("{")
    lines.append("    const double x = (jd - 2451545.0) / 36525.0;")
    lines.append("    const double xs = x / 100.0;")
    lines.append("    double v = MoonSunRate * x;")
    lines.append("    double p = 1.0;")
    lines.append("    for (int i = 0; i < 4; ++i) { v += MoonSunPolynomial[i] * p; p *= xs; }")
    lines.append("    for (const EnvelopeTerm &e : MoonSunEnvelopes)")
    lines.append("    {")
    lines.append("        const double c = std::cos(e.omega * x);")
    lines.append("        const double s = std::sin(e.omega * x);")
    lines.append("        double q = 1.0;")
    lines.append("        for (int m = 0; m <= e.degree; ++m)")
    lines.append("        {")
    lines.append("            v += (e.cosine[m] * c + e.sine[m] * s) * q;")
    lines.append("            q *= xs;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return v - MoonSunOffset;")
    lines.append("}")
    lines.append("")
    lines.append("inline double moonSunDifference(double jd) noexcept")
    lines.append("{")
    lines.append("    const double v = std::fmod(moonSunDifferenceUnwrapped(jd), 360.0);")
    lines.append("    return v < 0.0 ? v + 360.0 : v;")
    lines.append("}")
    lines.append("")
    lines.append("inline double moonLongitude(double jd) noexcept")
    lines.append("{")
    lines.append("    const double v = std::fmod(sunLongitude(jd) + moonSunDifference(jd), 360.0);")
    lines.append("    return v < 0.0 ? v + 360.0 : v;")
    lines.append("}")
    lines.append("")
    lines.append("// Correction relative to CumulativeDayMean * m (m is the continuous month")
    lines.append("// count).  It includes the quadratic/cubic trend, so it is not the pointwise")
    lines.append("// fit residual; see FIT_REPORT.md section 2.3.")
    lines.append("inline double cumulativeDayResidual(std::int64_t monthAbsolute) noexcept")
    lines.append("{")
    lines.append("    const double m = static_cast<double>(monthAbsolute) - (monthAbsolute > 0 ? 1.0 : 0.0);")
    lines.append("    const double x = m / 1000.0;")
    lines.append("    double total = 0.0;")
    lines.append("    double p = 1.0;")
    lines.append("    for (double c : CumulativeDayPolynomial) { total += c * p; p *= x; }")
    lines.append("    return total - CumulativeDayIntercept - CumulativeDayMean * m;")
    lines.append("}")
    lines.append("")
    lines.append("inline double synodicYearLength(std::int64_t yearAbsolute) noexcept")
    lines.append("{")
    lines.append("    const double x = (static_cast<double>(yearAbsolute) - 1.0) / 1000.0;")
    lines.append("    double v = 0.0;")
    lines.append("    double p = 1.0;")
    lines.append("    for (double c : SynodicYearPolynomial) { v += c * p; p *= x; }")
    lines.append("    return v;")
    lines.append("}")
    lines.append("")
    lines.append("inline double tropicalYearLength(std::int64_t yearAbsolute) noexcept")
    lines.append("{")
    lines.append("    const double x = (static_cast<double>(yearAbsolute) - 1.0) / 1000.0;")
    lines.append("    double v = 0.0;")
    lines.append("    double p = 1.0;")
    lines.append("    for (double c : TropicalYearPolynomial) { v += c * p; p *= x; }")
    lines.append("    return v;")
    lines.append("}")
    lines.append("")
    lines.append("// Leap months follow the astronomical no-mid-term rule, not a periodic bitmap.")
    lines.append("// A time-only Waveform score cannot represent it; see FIT_REPORT.md.  The")
    lines.append("// rule validated on this data uses sunLongitude() to count the 12 mid-terms")
    lines.append("// (multiples of 30 degrees) in each lunar month and marks the first empty")
    lines.append("// month of a 13-month synodic year as leap.")
    lines.append("//")
    lines.append("// Number of 30-degree boundaries crossed in [startJd, endJd); 0 means the")
    lines.append("// lunar month has no 中气.  Use this with new-moon times from")
    lines.append("// moonSunDifferenceUnwrapped() to implement isLeapMonth/isLeapYear.")
    lines.append("inline int midTermCount(double startJd, double endJd) noexcept")
    lines.append("{")
    lines.append("    const double l0 = sunLongitudeUnwrapped(startJd);")
    lines.append("    const double l1 = sunLongitudeUnwrapped(endJd);")
    lines.append("    return static_cast<int>(std::floor(l1 / 30.0) - std::floor(l0 / 30.0));")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace temporal::natural::data")
    lines.append("")
    HEADER.write_text("\n".join(lines), encoding="utf-8")


