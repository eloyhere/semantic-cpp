"""Generates bunch/casefold_data.h from Python's str.casefold().

Python's str.casefold() implements the full case folding of Unicode
CaseFolding.txt (statuses C + F, i.e. the mappings used for caseless
matching).  The generated header is a build artefact of this script, not
hand-edited code.

Usage:
    python tools/gen_casefold_data.py           # regenerate the header
    python tools/gen_casefold_data.py --check   # verify it is up to date

The generated header contains only ASCII source text: code points are written
as hexadecimal numbers, never as literal characters.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

UNICODE_VERSION = "15.0.0"
MAX_CP = 0x110000
SURROGATE_START = 0xD800
SURROGATE_END = 0xDFFF
MAX_HEADER_BYTES = 300 * 1024
TARGET = Path(__file__).resolve().parent.parent / "bunch" / "casefold_data.h"


def is_surrogate(cp: int) -> bool:
    return SURROGATE_START <= cp <= SURROGATE_END


def build_table():
    """Returns (entries, pool) for every code point whose full case folding
    differs from itself.  entries are (codepoint, pool offset, length)."""
    entries = []
    pool = []
    for cp in range(MAX_CP):
        if is_surrogate(cp):
            continue
        folded = chr(cp).casefold()
        if folded == chr(cp):
            continue
        mapping = [ord(character) for character in folded]
        entries.append((cp, len(pool), len(mapping)))
        pool.extend(mapping)
    return entries, pool


def chunk_lines(values, per_line, formatter):
    lines = []
    for index in range(0, len(values), per_line):
        chunk = values[index:index + per_line]
        lines.append("        " + ", ".join(formatter(value) for value in chunk) + ",")
    return lines


def generate():
    entries, pool = build_table()

    out = []
    out.append("#pragma once")
    out.append("")
    out.append("// Generated by tools/gen_casefold_data.py from Python's str.casefold()")
    out.append(f"// (Unicode {UNICODE_VERSION}). Do not edit by hand.")
    out.append("//")
    out.append("// Full Unicode case folding: CaseFolding.txt statuses C and F, which is")
    out.append("// the mapping set str.casefold() applies.  The table is sorted by code")
    out.append("// point so casefold() can binary-search it.  The language-dependent")
    out.append("// Turkic (T) mappings for U+0049 and U+0130 live in casefold.h.")
    out.append("")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace bunch")
    out.append("{")
    out.append("namespace detail")
    out.append("{")
    out.append("namespace unicode")
    out.append("{")
    out.append(f'inline constexpr const char *kCaseFoldVersion = "{UNICODE_VERSION}";')
    out.append("")
    out.append("struct CaseFoldEntry")
    out.append("{")
    out.append("    std::uint32_t codepoint;")
    out.append("    std::uint32_t offset;")
    out.append("    std::uint8_t length;")
    out.append("};")
    out.append("")
    out.append("inline constexpr CaseFoldEntry kCaseFoldTable[] = {")
    out.extend(chunk_lines(entries, 4, lambda e: f"{{0x{e[0]:X}, {e[1]}, {e[2]}}}"))
    out.append("};")
    out.append("")
    out.append("inline constexpr std::uint32_t kCaseFoldPool[] = {")
    out.extend(chunk_lines(pool, 12, lambda value: f"0x{value:X}"))
    out.append("};")
    out.append("")
    out.append("inline constexpr std::size_t kCaseFoldCount =")
    out.append("    sizeof(kCaseFoldTable) / sizeof(kCaseFoldTable[0]);")
    out.append("")
    out.append("inline const CaseFoldEntry *findCaseFold(std::uint32_t codepoint)")
    out.append("{")
    out.append("    std::size_t low = 0;")
    out.append("    std::size_t high = kCaseFoldCount;")
    out.append("    while (low < high)")
    out.append("    {")
    out.append("        const std::size_t middle = low + (high - low) / 2;")
    out.append("        if (kCaseFoldTable[middle].codepoint < codepoint)")
    out.append("        {")
    out.append("            low = middle + 1;")
    out.append("        }")
    out.append("        else")
    out.append("        {")
    out.append("            high = middle;")
    out.append("        }")
    out.append("    }")
    out.append("    if (low < kCaseFoldCount && kCaseFoldTable[low].codepoint == codepoint)")
    out.append("    {")
    out.append("        return &kCaseFoldTable[low];")
    out.append("    }")
    out.append("    return nullptr;")
    out.append("}")
    out.append("")
    out.append("} // namespace unicode")
    out.append("} // namespace detail")
    out.append("} // namespace bunch")
    out.append("")
    return "\n".join(out), entries, pool


def main(argv) -> int:
    arguments = argv[1:]
    check = False
    for argument in arguments:
        if argument == "--check":
            check = True
        else:
            print(f"error: unknown argument {argument!r}", file=sys.stderr)
            print("usage: gen_casefold_data.py [--check]", file=sys.stderr)
            return 2

    if unicodedata.unidata_version != UNICODE_VERSION:
        print(
            f"error: Python's Unicode database is {unicodedata.unidata_version}, "
            f"but this generator produces Unicode {UNICODE_VERSION} data",
            file=sys.stderr,
        )
        return 2

    content, entries, pool = generate()
    if any(ord(character) > 0x7F for character in content):
        print("error: generated header would contain non-ASCII source text", file=sys.stderr)
        return 2

    encoded = content.encode("ascii")
    if len(encoded) > MAX_HEADER_BYTES:
        print(
            f"error: generated header is {len(encoded)} bytes, over the {MAX_HEADER_BYTES} byte budget",
            file=sys.stderr,
        )
        return 2

    if check:
        if not TARGET.exists():
            print(f"error: missing {TARGET}", file=sys.stderr)
            return 1
        try:
            # Compare raw ASCII bytes so a CRLF conversion or a stray non-ASCII
            # character is reported as a mismatch instead of being normalised.
            current = TARGET.read_bytes().decode("ascii")
        except UnicodeDecodeError:
            print(
                f"error: {TARGET.name} contains non-ASCII bytes; run tools/gen_casefold_data.py",
                file=sys.stderr,
            )
            return 1
        if current == content:
            print(f"{TARGET.name} is up to date: {len(entries)} mappings, {len(pool)} code points")
            return 0
        current_lines = current.splitlines()
        new_lines = content.splitlines()
        difference = 0
        while difference < min(len(current_lines), len(new_lines)) and (
            current_lines[difference] == new_lines[difference]
        ):
            difference += 1
        print(
            f"error: {TARGET.name} is out of date "
            f"(first difference at line {difference + 1}); run tools/gen_casefold_data.py",
            file=sys.stderr,
        )
        return 1

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="ascii", newline="\n")
    print(f"wrote {TARGET} ({TARGET.stat().st_size} bytes)")
    print(f"casefold mappings={len(entries)} pool={len(pool)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
