"""Generates bunch/unicode_data.h from Python's unicodedata.

The generated header contains the Unicode 15.0 tables needed for
NFC/NFD/NFKC/NFKD normalisation and locale-aware case mapping.  It is a build
artefact of this script, not hand-edited code.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

MAX_CP = 0x110000
SURROGATE_START = 0xD800
SURROGATE_END = 0xDFFF


def is_surrogate(cp: int) -> bool:
    return SURROGATE_START <= cp <= SURROGATE_END


def hex_list(values, per_line=10):
    lines = []
    for index in range(0, len(values), per_line):
        chunk = values[index:index + per_line]
        lines.append("        " + ", ".join(chunk))
    return "\n".join(lines)


def build_decompositions():
    entries = []
    pool = []
    for cp in range(MAX_CP):
        if is_surrogate(cp):
            continue
        text = unicodedata.decomposition(chr(cp))
        if not text:
            continue
        parts = text.split()
        compatibility = 0
        if parts[0].startswith("<"):
            compatibility = 1
            parts = parts[1:]
        mapping = [int(part, 16) for part in parts]
        entries.append((cp, len(pool), len(mapping), compatibility))
        pool.extend(mapping)
    return entries, pool


def build_combining_classes():
    return [
        (cp, unicodedata.combining(chr(cp)))
        for cp in range(MAX_CP)
        if not is_surrogate(cp) and unicodedata.combining(chr(cp))
    ]


def build_compositions():
    compositions = []
    for cp in range(MAX_CP):
        if is_surrogate(cp):
            continue
        text = unicodedata.decomposition(chr(cp))
        if not text or text.startswith("<"):
            continue
        parts = text.split()
        if len(parts) != 2:
            continue
        first, second = int(parts[0], 16), int(parts[1], 16)
        if unicodedata.normalize("NFC", chr(first) + chr(second)) == chr(cp):
            compositions.append((first, second, cp))
    compositions.sort(key=lambda item: (item[0], item[1]))
    for index in range(1, len(compositions)):
        if compositions[index - 1][:2] == compositions[index][:2]:
            raise SystemExit(f"duplicate composition pair {compositions[index][:2]!r}")
    return compositions


def build_case_table(function):
    entries = []
    pool = []
    for cp in range(MAX_CP):
        if is_surrogate(cp):
            continue
        mapped = function(chr(cp))
        if mapped == chr(cp):
            continue
        entries.append((cp, len(pool), len(mapped)))
        pool.extend(ord(character) for character in mapped)
    return entries, pool


def build_ranges(predicate):
    ranges = []
    start = None
    previous = None
    for cp in range(MAX_CP):
        value = not is_surrogate(cp) and predicate(chr(cp))
        if value:
            if start is None:
                start = cp
            previous = cp
        elif start is not None:
            ranges.append((start, previous))
            start = None
    if start is not None:
        ranges.append((start, previous))
    return ranges


def is_letter(character: str) -> bool:
    return unicodedata.category(character).startswith("L")


def is_word(character: str) -> bool:
    if character in ("'", "\u2019"):
        return True
    return unicodedata.category(character)[0] in ("L", "M", "N") or unicodedata.category(character) == "Pc"


def is_cased(character: str) -> bool:
    return (
        unicodedata.category(character) in ("Lu", "Ll", "Lt")
        or character.lower() != character
        or character.upper() != character
    )


def emit_table(name, rows, formatter, per_line=8):
    if rows:
        body = ",\n".join(
            "        " + ", ".join(formatter(row) for row in rows[index:index + per_line])
            for index in range(0, len(rows), per_line)
        )
        return f"inline constexpr {name} = {{\n{body}\n}};\n"
    return f"inline constexpr {name} = {{}};\n"


def main() -> int:
    decompositions, decomposition_pool = build_decompositions()
    combining_classes = build_combining_classes()
    compositions = build_compositions()
    lower_entries, lower_pool = build_case_table(str.lower)
    upper_entries, upper_pool = build_case_table(str.upper)
    title_entries, title_pool = build_case_table(str.title)
    word_ranges = build_ranges(is_word)
    cased_ranges = build_ranges(is_cased)
    letter_ranges = build_ranges(is_letter)

    out = []
    out.append("#pragma once")
    out.append("")
    out.append("// Generated by tools/gen_unicode.py from Unicode "
               f"{unicodedata.unidata_version} data. Do not edit by hand.")
    out.append("// Regenerate after changing the Unicode version; the tables are sorted by")
    out.append("// code point so lookups can use binary search.")
    out.append("")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace bunch")
    out.append("{")
    out.append("namespace detail")
    out.append("{")
    out.append("namespace unicode")
    out.append("{")
    out.append(f'inline constexpr const char *kVersion = "{unicodedata.unidata_version}";')
    out.append("")
    out.append("struct Decomposition")
    out.append("{")
    out.append("    std::uint32_t codepoint;")
    out.append("    std::uint32_t offset;")
    out.append("    std::uint8_t length;")
    out.append("    std::uint8_t compatibility;")
    out.append("};")
    out.append("")
    out.append("struct CombiningClass")
    out.append("{")
    out.append("    std::uint32_t codepoint;")
    out.append("    std::uint8_t value;")
    out.append("};")
    out.append("")
    out.append("struct Composition")
    out.append("{")
    out.append("    std::uint32_t first;")
    out.append("    std::uint32_t second;")
    out.append("    std::uint32_t composed;")
    out.append("};")
    out.append("")
    out.append("struct CaseMapping")
    out.append("{")
    out.append("    std::uint32_t codepoint;")
    out.append("    std::uint32_t offset;")
    out.append("    std::uint8_t length;")
    out.append("};")
    out.append("")
    out.append("struct CodepointRange")
    out.append("{")
    out.append("    std::uint32_t first;")
    out.append("    std::uint32_t last;")
    out.append("};")
    out.append("")

    out.append(emit_table(
        "Decomposition kDecompositions[]", decompositions,
        lambda row: f"{{0x{row[0]:X}, {row[1]}, {row[2]}, {row[3]}}}", per_line=4))
    out.append(emit_table(
        "std::uint32_t kDecompositionPool[]", decomposition_pool,
        lambda row: f"0x{row:X}", per_line=10))
    out.append(emit_table(
        "CombiningClass kCombiningClasses[]", combining_classes,
        lambda row: f"{{0x{row[0]:X}, {row[1]}}}", per_line=6))
    out.append(emit_table(
        "Composition kCompositions[]", compositions,
        lambda row: f"{{0x{row[0]:X}, 0x{row[1]:X}, 0x{row[2]:X}}}", per_line=4))

    for prefix, entries, pool in (
        ("Lowercase", lower_entries, lower_pool),
        ("Uppercase", upper_entries, upper_pool),
        ("Titlecase", title_entries, title_pool),
    ):
        out.append(emit_table(
            f"CaseMapping k{prefix}Mappings[]", entries,
            lambda row: f"{{0x{row[0]:X}, {row[1]}, {row[2]}}}", per_line=5))
        out.append(emit_table(
            f"std::uint32_t k{prefix}Pool[]", pool,
            lambda row: f"0x{row:X}", per_line=10))

    for name, ranges in (("kWordRanges", word_ranges), ("kCasedRanges", cased_ranges), ("kLetterRanges", letter_ranges)):
        out.append(emit_table(
            f"CodepointRange {name}[]", ranges,
            lambda row: f"{{0x{row[0]:X}, 0x{row[1]:X}}}", per_line=5))

    out.append("inline constexpr std::size_t kDecompositionCount = sizeof(kDecompositions) / sizeof(kDecompositions[0]);")
    out.append("inline constexpr std::size_t kCombiningClassCount = sizeof(kCombiningClasses) / sizeof(kCombiningClasses[0]);")
    out.append("inline constexpr std::size_t kCompositionCount = sizeof(kCompositions) / sizeof(kCompositions[0]);")
    out.append("inline constexpr std::size_t kLowercaseCount = sizeof(kLowercaseMappings) / sizeof(kLowercaseMappings[0]);")
    out.append("inline constexpr std::size_t kUppercaseCount = sizeof(kUppercaseMappings) / sizeof(kUppercaseMappings[0]);")
    out.append("inline constexpr std::size_t kTitlecaseCount = sizeof(kTitlecaseMappings) / sizeof(kTitlecaseMappings[0]);")
    out.append("")
    out.append("inline const Decomposition *findDecomposition(std::uint32_t codepoint)")
    out.append("{")
    out.append("    std::size_t low = 0;")
    out.append("    std::size_t high = kDecompositionCount;")
    out.append("    while (low < high)")
    out.append("    {")
    out.append("        const std::size_t middle = low + (high - low) / 2;")
    out.append("        if (kDecompositions[middle].codepoint < codepoint)")
    out.append("        {")
    out.append("            low = middle + 1;")
    out.append("        }")
    out.append("        else")
    out.append("        {")
    out.append("            high = middle;")
    out.append("        }")
    out.append("    }")
    out.append("    if (low < kDecompositionCount && kDecompositions[low].codepoint == codepoint)")
    out.append("    {")
    out.append("        return &kDecompositions[low];")
    out.append("    }")
    out.append("    return nullptr;")
    out.append("}")
    out.append("")
    out.append("inline std::uint8_t combiningClass(std::uint32_t codepoint)")
    out.append("{")
    out.append("    std::size_t low = 0;")
    out.append("    std::size_t high = kCombiningClassCount;")
    out.append("    while (low < high)")
    out.append("    {")
    out.append("        const std::size_t middle = low + (high - low) / 2;")
    out.append("        if (kCombiningClasses[middle].codepoint < codepoint)")
    out.append("        {")
    out.append("            low = middle + 1;")
    out.append("        }")
    out.append("        else")
    out.append("        {")
    out.append("            high = middle;")
    out.append("        }")
    out.append("    }")
    out.append("    if (low < kCombiningClassCount && kCombiningClasses[low].codepoint == codepoint)")
    out.append("    {")
    out.append("        return kCombiningClasses[low].value;")
    out.append("    }")
    out.append("    return 0;")
    out.append("}")
    out.append("")
    out.append("inline bool compose(std::uint32_t first, std::uint32_t second, std::uint32_t &composed)")
    out.append("{")
    out.append("    std::size_t low = 0;")
    out.append("    std::size_t high = kCompositionCount;")
    out.append("    while (low < high)")
    out.append("    {")
    out.append("        const std::size_t middle = low + (high - low) / 2;")
    out.append("        const Composition &candidate = kCompositions[middle];")
    out.append("        if (candidate.first < first || (candidate.first == first && candidate.second < second))")
    out.append("        {")
    out.append("            low = middle + 1;")
    out.append("        }")
    out.append("        else")
    out.append("        {")
    out.append("            high = middle;")
    out.append("        }")
    out.append("    }")
    out.append("    if (low < kCompositionCount && kCompositions[low].first == first && kCompositions[low].second == second)")
    out.append("    {")
    out.append("        composed = kCompositions[low].composed;")
    out.append("        return true;")
    out.append("    }")
    out.append("    return false;")
    out.append("}")
    out.append("")
    out.append("inline const CaseMapping *findCaseMapping(const CaseMapping *table, std::size_t count, std::uint32_t codepoint)")
    out.append("{")
    out.append("    std::size_t low = 0;")
    out.append("    std::size_t high = count;")
    out.append("    while (low < high)")
    out.append("    {")
    out.append("        const std::size_t middle = low + (high - low) / 2;")
    out.append("        if (table[middle].codepoint < codepoint)")
    out.append("        {")
    out.append("            low = middle + 1;")
    out.append("        }")
    out.append("        else")
    out.append("        {")
    out.append("            high = middle;")
    out.append("        }")
    out.append("    }")
    out.append("    if (low < count && table[low].codepoint == codepoint)")
    out.append("    {")
    out.append("        return &table[low];")
    out.append("    }")
    out.append("    return nullptr;")
    out.append("}")
    out.append("")
    out.append("inline bool inRanges(const CodepointRange *ranges, std::size_t count, std::uint32_t codepoint)")
    out.append("{")
    out.append("    std::size_t low = 0;")
    out.append("    std::size_t high = count;")
    out.append("    while (low < high)")
    out.append("    {")
    out.append("        const std::size_t middle = low + (high - low) / 2;")
    out.append("        if (ranges[middle].last < codepoint)")
    out.append("        {")
    out.append("            low = middle + 1;")
    out.append("        }")
    out.append("        else")
    out.append("        {")
    out.append("            high = middle;")
    out.append("        }")
    out.append("    }")
    out.append("    return low < count && ranges[low].first <= codepoint;")
    out.append("}")
    out.append("")
    out.append("inline bool isWord(std::uint32_t codepoint)")
    out.append("{")
    out.append("    return inRanges(kWordRanges, sizeof(kWordRanges) / sizeof(kWordRanges[0]), codepoint);")
    out.append("}")
    out.append("")
    out.append("inline bool isCased(std::uint32_t codepoint)")
    out.append("{")
    out.append("    return inRanges(kCasedRanges, sizeof(kCasedRanges) / sizeof(kCasedRanges[0]), codepoint);")
    out.append("}")
    out.append("")
    out.append("inline bool isLetter(std::uint32_t codepoint)")
    out.append("{")
    out.append("    return inRanges(kLetterRanges, sizeof(kLetterRanges) / sizeof(kLetterRanges[0]), codepoint);")
    out.append("}")
    out.append("")
    out.append("} // namespace unicode")
    out.append("} // namespace detail")
    out.append("} // namespace bunch")
    out.append("")

    target = Path(__file__).resolve().parent.parent / "bunch" / "unicode_data.h"
    target.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {target} ({target.stat().st_size} bytes)")
    print(f"decompositions={len(decompositions)} pool={len(decomposition_pool)}")
    print(f"combining={len(combining_classes)} compositions={len(compositions)}")
    print(f"case lower={len(lower_entries)}/{len(lower_pool)} upper={len(upper_entries)}/{len(upper_pool)} title={len(title_entries)}/{len(title_pool)}")
    print(f"ranges word={len(word_ranges)} cased={len(cased_ranges)} letter={len(letter_ranges)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
